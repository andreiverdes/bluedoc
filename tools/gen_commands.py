#!/usr/bin/env python3
"""Generate every agent's /bluedoc-<name> slash command files from commands/commands.json, the one place commands
are edited. Run it after editing the spec; `--check` writes nothing and exits 1 when a generated file differs from
the spec, is missing or is stale.

The spec is a JSON array of {name, description, args, kind, prompt?, run?}: `name` without the `bluedoc-` prefix,
`args` the argument hint, `kind` prompt (an agent turn with `prompt`) or action (`run`: a bundled script and its
args, the user's arguments as a last "{{args}}" element, split shell-style). Output:

  commands/bluedoc-<name>.md                     Claude Code (and omp, which shows them as /bluedoc:bluedoc-<name>
                                                 and runs no `!` lines: its extension registers the working ones).
                                                 $ARGUMENTS and !`…` with ${CLAUDE_PLUGIN_ROOT}:
                                                 https://code.claude.com/docs/en/skills (string substitutions,
                                                 dynamic context injection)
  com.github.copilot/commands/bluedoc-<name>.md  Copilot CLI: an Agent Plugins plugin reads commands only from
                                                 com.github.copilot/commands/ (https://docs.github.com/en/copilot/
                                                 reference/copilot-cli-reference/cli-plugin-reference) and loads each
                                                 as a skill whose base directory is that folder. No documented `!`
                                                 lines or plugin-root variable, so actions ask the agent to run the
                                                 script at ../../skills/bluedoc/scripts from that base directory
  antigravity/skills/bluedoc-<name>/SKILL.md     Antigravity CLI (agy): a plugin's skills are its slash commands
                                                 (/<skill>, the plugin's own skills/ folder: agy 1.4.0's bundled
                                                 agy-customizations docs/skills.md and migrate-workflows skill). agy
                                                 documents no argument substitution, `!` lines or plugin-root variable
                                                 in skills, so the user's text after the command is the request and
                                                 actions ask the agent to run the script at ../bluedoc/scripts from
                                                 the skill's folder (antigravity/skills/bluedoc links the skill)

Codex gets no files: its plugins load skills only from the fixed root skills/ folder (no Codex-only skills path in
extensions.com.openai: https://developers.openai.com/plugins/build/plugins.md), so command skills would reach every
agent. Codex users ask for `$bluedoc <request>`. pi registers the commands itself from the spec
(extensions/bluedoc.ts)."""
from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = Path("commands/commands.json")
PREFIX = "bluedoc-"
ARGS = "{{args}}"
SCRIPTS = ("serve.py", "build.py")
NOTICE = "Generated by tools/gen_commands.py from commands/commands.json: edit the spec, then run it."
ACTION_TAIL = "Show me the output above as it is. Run nothing else."
AGY_ARGS = "the text I typed after the command"
# each target: the folder of generated files, their suffix and the function that renders one command
TARGETS = {}


def target(folder: str, suffix: str):
    def register(fn):
        TARGETS[folder] = (suffix, fn)
        return fn
    return register


def check_spec(spec) -> list[str]:
    """Problems with the spec, as lines; none when every command can be generated for every agent."""
    if not isinstance(spec, list):
        return ["the spec must be a JSON array"]
    errors, seen = [], set()
    for i, c in enumerate(spec):
        where = f"commands[{i}]"
        if not isinstance(c, dict):
            errors.append(f"{where}: not an object")
            continue
        name = c.get("name")
        if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9-]*", name) or name.startswith(PREFIX):
            errors.append(f"{where}.name: lowercase letters, digits and -, without the {PREFIX} prefix")
        elif name in seen:
            errors.append(f"{where}.name: {name} twice")
        seen.add(name)
        for key in ("description", "args"):
            if not isinstance(c.get(key), str) or "\n" in c[key]:
                errors.append(f"{where}.{key}: one line of text")
        if not (c.get("description") or "").strip():
            errors.append(f"{where}.description: empty")
        kind = c.get("kind")
        if kind == "prompt":
            if not isinstance(c.get("prompt"), str) or ARGS not in c["prompt"]:
                errors.append(f"{where}.prompt: text with {ARGS}")
            if "run" in c:
                errors.append(f"{where}.run: only an action runs a script")
        elif kind == "action":
            run = c.get("run")
            if not isinstance(run, dict) or run.get("script") not in SCRIPTS:
                errors.append(f"{where}.run.script: one of {', '.join(SCRIPTS)}")
            elif not isinstance(run.get("args"), list) or not all(isinstance(a, str) and a for a in run["args"]):
                errors.append(f"{where}.run.args: a list of strings")
            elif any(ARGS in a for a in run["args"][:-1]) or (run["args"] and ARGS in run["args"][-1]
                                                              and run["args"][-1] != ARGS):
                errors.append(f"{where}.run.args: {ARGS} only as the last element, on its own")
            if "prompt" in c:
                errors.append(f"{where}.prompt: an action has run, not prompt")
        else:
            errors.append(f"{where}.kind: prompt or action")
    return errors


def run_words(c: dict) -> tuple[str, list[str], bool]:
    """An action's script, its fixed args shell-quoted, and whether the user's arguments follow them."""
    args = c["run"]["args"]
    takes = bool(args) and args[-1] == ARGS
    return c["run"]["script"], [shlex.quote(a) for a in (args[:-1] if takes else args)], takes


def frontmatter(fields: dict[str, str]) -> str:
    """YAML frontmatter, every value a double-quoted string (JSON's escapes are YAML's)."""
    lines = [f"# {NOTICE}"] + [f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in fields.items() if v]
    return "---\n" + "\n".join(lines) + "\n---\n\n"


@target("commands", ".md")
def claude(c: dict) -> str:
    fields = {"description": c["description"], "argument-hint": c["args"]}
    if c["kind"] == "prompt":
        return frontmatter(fields) + c["prompt"].replace(ARGS, "$ARGUMENTS") + "\n"
    script, words, takes = run_words(c)
    line = " ".join([f'python3 "${{CLAUDE_PLUGIN_ROOT}}/skills/bluedoc/scripts/{script}"', *words]
                    + (["$ARGUMENTS"] if takes else []))
    return frontmatter({**fields, "allowed-tools": "Bash(python3:*)"}) + f"!`{line}`\n\n{ACTION_TAIL}\n"


@target("com.github.copilot/commands", ".md")
def copilot(c: dict) -> str:
    fields = {"description": c["description"], "argument-hint": c["args"]}
    if c["kind"] == "prompt":
        return frontmatter(fields) + c["prompt"].replace(ARGS, "$ARGUMENTS") + "\n"
    script, words, takes = run_words(c)
    line = " ".join([f"python3 <base>/../../skills/bluedoc/scripts/{script}", *words] + (["$ARGUMENTS"] if takes else []))
    return (frontmatter({**fields, "allowed-tools": "shell(python3:*)"}) + f"Run `{line}`, where `<base>` is this "
            f"skill's base directory, and show me its output as it is. Run nothing else.\n")


@target("antigravity/skills", "/SKILL.md")
def antigravity(c: dict) -> str:
    fields = {"name": f"{PREFIX}{c['name']}", "description": c["description"]}
    if c["kind"] == "prompt":
        return frontmatter(fields) + c["prompt"].replace(ARGS, f"{AGY_ARGS} ({c['args']})") + "\n"
    script, words, takes = run_words(c)
    line = " ".join([f"python3 <skill>/../bluedoc/scripts/{script}", *words] + (["<args>"] if takes else []))
    tail = f", `<args>` being {AGY_ARGS} ({c['args']}; leave it out when there is none)" if takes else ""
    return (frontmatter(fields) + f"Run `{line}`, where `<skill>` is this skill's folder{tail}, and show me its "
            "output as it is. Run nothing else.\n")


def render(spec: list[dict]) -> dict[Path, str]:
    """Every generated file, by path relative to the repo root."""
    return {Path(folder) / f"{PREFIX}{c['name']}{suffix}": fn(c)
            for folder, (suffix, fn) in TARGETS.items() for c in spec}


def stale(root: Path, files: dict[Path, str]) -> list[Path]:
    """Generated-looking files the spec no longer names."""
    return sorted(p.relative_to(root) for folder, (suffix, _) in TARGETS.items()
                  for p in (root / folder).glob(f"{PREFIX}*{suffix}") if p.relative_to(root) not in files)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when a generated file is out of date")
    ap.add_argument("--root", type=Path, default=ROOT, help="the repo to read the spec from and write into")
    a = ap.parse_args(argv)
    try:
        spec = json.loads((a.root / SPEC).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        print(f"cannot read {a.root / SPEC}: {e}", file=sys.stderr)
        return 2
    errors = check_spec(spec)
    if errors:
        print("\n".join(f"{SPEC}: {e}" for e in errors), file=sys.stderr)
        return 2
    files = render(spec)
    changed = [p for p, text in files.items()
               if not (a.root / p).is_file() or (a.root / p).read_text(encoding="utf-8") != text]
    extra = stale(a.root, files)
    if a.check:
        for p in changed:
            print(f"out of date: {p}", file=sys.stderr)
        for p in extra:
            print(f"stale: {p} (not in {SPEC})", file=sys.stderr)
        if changed or extra:
            print("run python3 tools/gen_commands.py to regenerate", file=sys.stderr)
            return 1
        return 0
    for p in changed:
        (a.root / p).parent.mkdir(parents=True, exist_ok=True)
        (a.root / p).write_text(files[p], encoding="utf-8")
    for p in extra:
        (a.root / p).unlink()
        if p.name == "SKILL.md" and not any((a.root / p).parent.iterdir()):
            (a.root / p).parent.rmdir()   # an Antigravity command's own folder
    print(f"{len(spec)} commands: wrote {len(changed)} file(s), removed {len(extra)}, {len(files)} in all", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
